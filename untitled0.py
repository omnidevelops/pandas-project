import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
from pathlib import Path

# 1. Find the folder where this program is running
folder = Path.cwd()

# 2. Create sample CSV files only when they are missing
dates = pd.date_range("2026-01-01", periods=7, freq="D")
cities = ["Lucknow", "Mumbai", "Ghaziabad"]

traffic_values = {
    "Lucknow": [58, 62, 65, 60, 67, 63, 70],
    "Mumbai": [78, 82, 80, 85, 83, 88, 86],
    "Ghaziabad": [68, 72, 75, 73, 78, 76, 80]
}

aqi_values = {
    "Lucknow": [155, 162, 148, 170, 165, 158, 175],
    "Mumbai": [92, 105, 98, 110, 101, 115, 108],
    "Ghaziabad": [185, 195, 190, 205, 198, 210, 202]
}

temperature_values = {
    "Lucknow": [16, 17, 17.5, 18, 17, 16.5, 18],
    "Mumbai": [25, 25.5, 26, 26, 25.5, 26.5, 27],
    "Ghaziabad": [14, 15, 15.5, 16, 15, 14.5, 16]
}

rainfall_values = {
    "Lucknow": [0, 0, 0.2, 0, 0, 0, 0],
    "Mumbai": [0, 1.2, 0, 0, 0.5, 0, 0],
    "Ghaziabad": [0, 0, 0, 0.1, 0, 0, 0]
}

if not (folder / "traffic.csv").exists():
    rows = []
    for city in cities:
        for i, date in enumerate(dates):
            rows.append([city, date.strftime("%Y-%m-%d"),
                         traffic_values[city][i]])
    pd.DataFrame(rows, columns=["City", "Date", "Traffic_Index"]).to_csv(
        folder / "traffic.csv", index=False
    )
    print("Created sample traffic.csv")

if not (folder / "air_quality.csv").exists():
    rows = []
    for city in cities:
        for i, date in enumerate(dates):
            rows.append([city, date.strftime("%Y-%m-%d"),
                         aqi_values[city][i]])
    pd.DataFrame(rows, columns=["City", "Date", "AQI"]).to_csv(
        folder / "air_quality.csv", index=False
    )
    print("Created sample air_quality.csv")

if not (folder / "weather.csv").exists():
    rows = []
    for city in cities:
        for i, date in enumerate(dates):
            rows.append([
                city, date.strftime("%Y-%m-%d"),
                temperature_values[city][i], rainfall_values[city][i]
            ])
    pd.DataFrame(
        rows,
        columns=["City", "Date", "Temperature_C", "Rainfall_mm"]
    ).to_csv(folder / "weather.csv", index=False)
    print("Created sample weather.csv")

# 3. Read the CSV files
traffic = pd.read_csv(folder / "traffic.csv")
air = pd.read_csv(folder / "air_quality.csv")
weather = pd.read_csv(folder / "weather.csv")

# 4. Keep only the selected cities
traffic = traffic[traffic["City"].isin(cities)].copy()
air = air[air["City"].isin(cities)].copy()
weather = weather[weather["City"].isin(cities)].copy()

# 5. Convert dates into the same format
for dataset in [traffic, air, weather]:
    dataset["Date"] = pd.to_datetime(dataset["Date"])